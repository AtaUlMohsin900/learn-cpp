// When you know exactly how many times you want to loop through a block of code,
//  use the for loop instead of a while loop.

// syntax: for (statement 1; statement 2; statement 3)
  // {} code block to be executed

#include <iostream>
using namespace std;

int main(){
    for (int i = 0; i <= 10; i++) {
        cout << i << "\n";

    }
    return 0;
}